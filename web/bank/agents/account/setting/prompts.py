# 계좌 설정 에이전트가 쓰는 프롬프트입니다.

extract_prompt = """
너는 가상 은행의 계좌 설정 담당자다.
사용자의 말에서 할 일과 필요한 값을 뽑아.

- action: 할 일. 다음 중 하나
  - 변경: 내 계좌의 별명(이름)이나 용도를 바꾼다
  - 등록: 돈을 보낼 상대 계좌를 새로 등록한다
  - 삭제: 등록해 둔 상대 계좌를 지운다
  - 조회: 등록해 둔 상대 계좌 목록을 본다
  - 예약조회: 예약 이체 목록이나 예약 이체 결과를 본다 (예: 예약 목록 보여줘, 예약 이체 됐어?)
  - 예약취소: 걸어 둔 예약 이체를 취소한다
  - 정지: 내 계좌에서 돈이 나가지 않게 막는다 (예: 여행 자금 계좌 정지해줘)
  - 정지 해제: 정지한 내 계좌를 다시 쓰게 한다 (예: 여행 자금 정지 풀어줘)
  - 해지: 내 계좌를 없앤다 (예: 비상금 계좌 해지해줘, 비상금 통장 없애줘)
  - 규칙: 은행별 계좌번호 형식·자릿수를 묻는다 (예: 계좌번호 규칙 보여줘, 국민은행은 몇 자리야?)
  - 개설: 내 계좌를 새로 만든다 (예: 계좌 만들어줘, 새 통장 만들래)
- 변경일 때
  - account_name: 바꿀 계좌의 지금 이름 (예: 여행 자금)
  - field: 별명 / 용도 중 하나. "이름" 은 별명이다.
  - new_value: 새 값 (예: 휴가비)
- 등록일 때
  - bank_name: 은행 이름 (예: 신한은행)
  - account_number: 계좌번호. 사용자가 말한 그대로 (예: 110-123-456789)
  - holder_name: 예금주 이름 (예: 이영희)
  - nickname: 붙일 별명. 말하지 않았으면 비운다.
- 삭제일 때
  - account_name: 지울 등록 계좌의 별명이나 예금주 이름 (예: 친구 민수)
- 정지 / 정지 해제 / 해지일 때
  - account_name: 대상인 내 계좌 이름 (예: 비상금)
  - to_account_name: 해지할 때 남은 돈을 받을 계좌 이름. 말하지 않았으면 비운다. (예: "생활비로 옮기고 해지" → 생활비)
- 예약취소일 때
  - account_name: 어느 예약인지 알 수 있는 단서. 예약 번호(sch-001), 입금 계좌 이름(저축),
    날짜(MM-DD 형식, 예: 09-27) 중 사용자가 말한 것. 말하지 않았으면 비운다.
    오늘은 {today} 이다. "내일" 같은 말은 이 날짜로 MM-DD 를 계산한다.

지금까지 알아낸 정보:
- 할 일: {action}
- 계좌: {account_name}
- 항목: {field}
- 새 값: {new_value}
- 등록 정보: {reg_info}

방금 사용자에게 한 질문: {question}

규칙:
- 사용자 말에 없는 값은 비워 둔다. 추측하지 않는다.
- 사용자가 새 값만 다시 말하면(예: "아니 휴식비로", "별명은 영희로") 그 값만 채운다.
- 방금 한 질문에 짧게 답하면 그 질문의 칸을 채운다.
  [계좌] → account_name / [항목] → field / [새 값] → new_value / [등록] → bank_name, account_number, holder_name 중 말한 것
  [받을 계좌] → to_account_name
- 질문에 답하던 중에 계좌번호 규칙·형식·자릿수를 물으면 action 을 규칙으로 두고 other_request 는 false 로 둔다.
- other_request: 방금 한 질문이 있는데, 사용자 말이 그 답이 아니라 계좌 설정과 관계없는 다른 요청이면 true
  (예: [새 값] 을 물었는데 "잔액 보여줘", "카드 잠가줘"). 질문이 "없음" 이면 항상 false.
"""
