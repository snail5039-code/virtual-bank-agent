# 2-2 처리안 제시 · 승인(interrupt) · 응답 해석 · 승인 대기 판정 확인용입니다.
# main.py 를 켜고 입력을 차례로 넣은 뒤, 화면에 나온 결과를 보여줍니다.
#
# 실행 : uv run python 테스트/2-2_승인_확인.py
#
# 확인할 것 (입력 순서대로)
#   1) 승인       : 처리안(출금·입금·금액·출금 후 잔액)이 나오고, "응, 진행해" 에 "승인되었습니다"
#                   → 분기 0 이 없으면 "응, 진행해" 가 새 요청으로 분류됩니다
#   2) 거절       : "아니 안 할래" 에 "진행하지 않았습니다"
#   3) 수정       : "아니, 5만원만" 에 금액이 50,000원으로 바뀐 처리안을 전부 다시 보여준다
#                   "입금은 여행 자금으로" 에 입금 계좌가 바뀐 처리안을 다시 보여준다 → 승인
#   4) 모름       : "음..." 에 "답을 알아듣지 못했습니다" 와 함께 같은 처리안을 다시 묻는다 → 취소
#   5) 끝난 뒤    : 계좌 조회가 새 요청으로 잘 돈다. 잔액은 바뀌지 않았다 (실제 이체는 2-4)
#
# 실제 이체(잔액 변경)는 아직 하지 않습니다. 2-3·2-4 단계에서 붙입니다.

import os
import subprocess
import sys

inputs = [
    "생활비에서 저축으로 10만원 보내줘",
    "1234",                     # 본인 확인 (3-5 부터. 세션에서 한 번만)
    "응, 진행해",
    "생활비에서 저축으로 10만원 보내줘",
    "아니 안 할래",
    "생활비에서 저축으로 10만원 보내줘",
    "아니, 5만원만",
    "입금은 여행 자금으로 해줘",
    "승인",
    "생활비에서 저축으로 3만원 보내줘",
    "음...",
    "취소할게",
    "내 계좌 잔액 보여줘",
    "종료",
]

result = subprocess.run(
    [sys.executable, "src/main.py"],
    input="\n".join(inputs) + "\n",
    capture_output=True,
    text=True,
    encoding="utf-8",
    env={**os.environ, "PYTHONIOENCODING": "utf-8"},
)

print("넣은 입력 :")
for text in inputs:
    print("  ", text)
print()
print("===== 화면 출력 =====")
print(result.stdout)
print(result.stderr)
